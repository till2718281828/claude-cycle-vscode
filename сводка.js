// Раздел «Требует внимания»: Markdown из пульт-сводка.json в папке проектов (формат — docs/pult-summary.md).
// Сводки нет (папка не задана или пульт не собран) — пример на вымышленных проектах с пометкой «демо».
// Модуль без зависимости от vscode — его покрывают тесты test/*.test.js (node --test).
const path = require('path');

const ФАЙЛ = 'пульт-сводка.json';
const ОБЯЗАТЕЛЬНЫЕ = ['требует_внимания', 'просрочено', 'ждёт_вас', 'в_работе', 'бэклог', 'задачи'];
const УРОВЕНЬ = { crit: 'сбой', warn: 'внимание', ok: 'норма' };

// Демо — вымышленная компания СтальКонструкт-Демо: то, что увидит владелец настоящего пульта.
const ДЕМО = {
  собран: '2026-10-09 06:00', требует_внимания: 4, просрочено: 1, ждёт_вас: 1, в_работе: 5,
  P1_в_работе: 2, лимит_P1: 3, бэклог: 12, проектов_с_циклом: 4, проектов: 5,
  сигналы: [{ проект: 'Закупки', текст: 'ночная выгрузка заказов поставщикам не пришла', уровень: 'crit', дата: '2026-10-09' }],
  задачи: [
    { проект: 'Казначейство', задача: 'Платёжный календарь: сверка с банком', статус: 'в работе', приоритет: 'P1',
      причины: ['просрочено на 1 дн.'] },
    { проект: 'Отчётность', задача: 'P&L за сентябрь: выпуск для совета директоров', статус: 'ждёт вас', приоритет: 'P1',
      причины: ['срок через 2 дн.'] },
    { проект: 'Бюджет', задача: 'Сценарии бюджета 2027', статус: 'в работе', приоритет: 'P2',
      причины: ['без движения 9 дн. (порог 7)'] }
  ]
};

// Тексты приходят из чужих файлов: разметку Markdown и HTML в них гасим, перевод строки — пробел.
const текст = v => String(v ?? '').replace(/\r?\n/g, ' ').replace(/[\\`*_[\]<>|]/g, c => '\\' + c);

function markdown(s) {
  const п = k => текст(s[k]);   // счётчики тоже из чужого файла: не число — показать как текст, без разметки
  const p1 = s['P1_в_работе'] > s['лимит_P1'] ? ` · **P1: ${п('P1_в_работе')} при лимите ${п('лимит_P1')}**` : '';
  let md = `# Требует внимания: ${п('требует_внимания')}\n\n` +
    `Просрочено **${п('просрочено')}** · ждёт вас **${п('ждёт_вас')}** · в работе ${п('в_работе')} · в бэклоге ${п('бэклог')}${p1}\n\n`;
  const сигналы = s['сигналы'] || [];
  if (сигналы.length) {
    md += '**Сигналы автоматов**\n\n' + сигналы.map(x =>
      `- **${УРОВЕНЬ[x['уровень']] || текст(x['уровень']) || '—'}** · ${текст(x['проект'])}: ${текст(x['текст'])}` +
      (x['дата'] ? ` (${текст(x['дата'])})` : '')).join('\n') + '\n\n';
  }
  md += s['задачи'].length
    ? '| Проект | Задача | Почему |\n|---|---|---|\n' +
      s['задачи'].map(t => `| ${текст(t['проект'])} | ${текст(t['задача'])}${t['приоритет'] ? ` (${текст(t['приоритет'])})` : ''} | ` +
        `${текст((t['причины'] || []).join('; '))} |`).join('\n') + '\n\n'
    : (сигналы.length ? '' : 'Ничего не горит.\n\n');
  // подвал — из необязательных полей: чего нет, того не пишем
  const подвал = [s['проектов'] !== undefined && `Проектов с циклом: ${текст(s['проектов_с_циклом'] ?? '—')} из ${п('проектов')}.`,
    s['собран'] && `Пульт собран ${текст(s['собран'])}.`].filter(Boolean).join(' ');
  return подвал ? md + подвал + '\n' : md;
}

const ошибка = m => `# Требует внимания\n\nСводка пульта не читается: ${текст(m)}.\n`;

// root — папка проектов (может быть пустой), read(путь, 'utf8') — чтение файла (fs.readFileSync).
function раздел(root, read) {
  let json;
  try {
    if (!root) throw Object.assign(new Error('нет папки'), { code: 'ENOENT' });
    json = read(path.join(root, ФАЙЛ), 'utf8');
  } catch (e) {
    // демо — только когда сводки нет; файл есть, но не читается — это ошибка, а не повод показать вымысел
    if (e.code !== 'ENOENT') return ошибка(e.message);
    return '> **Демо.** Пример на вымышленных проектах. Свой список появится, когда в настройке ' +
      '`cycleWelcome.projectsRoot` будет папка с `' + ФАЙЛ + '`; формат — `docs/pult-summary.md` в репозитории расширения.\n\n' + markdown(ДЕМО);
  }
  try {
    const s = JSON.parse(json);
    const нет = ОБЯЗАТЕЛЬНЫЕ.filter(k => s[k] === undefined || (k === 'задачи' && !Array.isArray(s[k])));
    if (нет.length) throw new Error('нет полей: ' + нет.join(', '));
    const нечисла = ОБЯЗАТЕЛЬНЫЕ.filter(k => k !== 'задачи' && typeof s[k] !== 'number');
    if (нечисла.length) throw new Error('не числа: ' + нечисла.join(', '));
    return markdown(s);
  } catch (e) {
    return ошибка(e.message);
  }
}

module.exports = { ФАЙЛ, ДЕМО, markdown, раздел };
