// Тесты раздела «Требует внимания»: сводка пульта, демо без неё, сломанный JSON. Запуск: node --test
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const м = require('../сводка.js');

const сводка = {
  собран: '2026-10-09 18:40', требует_внимания: 2, просрочено: 1, ждёт_вас: 1, в_работе: 3,
  P1_в_работе: 4, лимит_P1: 3, бэклог: 7, проектов_с_циклом: 2, проектов: 3,
  сигналы: [{ проект: 'Склад', текст: 'выгрузка не пришла', уровень: 'crit', дата: '2026-10-09' }],
  задачи: [{ проект: 'Отчёт', задача: 'Выпуск | сентябрь', статус: 'ждёт вас', приоритет: 'P1', срок: '2026-10-08',
    причины: ['просрочено на 1 дн.', 'без движения 5 дн. (порог 3)'] }]
};

test('валидная сводка: счётчики, сигналы по уровню, задачи таблицей', () => {
  assert.strictEqual(м.markdown(сводка),
    '# Требует внимания: 2\n\n' +
    'Просрочено **1** · ждёт вас **1** · в работе 3 · в бэклоге 7 · **P1: 4 при лимите 3**\n\n' +
    '**Сигналы автоматов**\n\n- **сбой** · Склад: выгрузка не пришла (2026-10-09)\n\n' +
    '| Проект | Задача | Почему |\n|---|---|---|\n' +
    '| Отчёт | Выпуск \\| сентябрь (P1) | просрочено на 1 дн.; без движения 5 дн. (порог 3) |\n\n' +
    'Проектов с циклом: 2 из 3. Пульт собран 2026-10-09 18:40.\n');
});

test('ничего не горит: без таблицы и без строки P1 в пределах лимита', () => {
  const md = м.markdown({ ...сводка, требует_внимания: 0, P1_в_работе: 1, сигналы: [], задачи: [] });
  assert.match(md, /Ничего не горит\./);
  assert.doesNotMatch(md, /при лимите|\| Проект/);
});

test('только обязательные поля: без подвала и без строки P1', () => {
  const md = м.markdown({ требует_внимания: 0, просрочено: 0, ждёт_вас: 0, в_работе: 1, бэклог: 2, задачи: [] });
  assert.strictEqual(md, '# Требует внимания: 0\n\nПросрочено **0** · ждёт вас **0** · в работе 1 · в бэклоге 2\n\nНичего не горит.\n\n');
});

test('нет папки проектов — демо с пометкой', () => {
  const md = м.раздел('', fs.readFileSync);
  assert.match(md, /демо/i);
  assert.match(md, /cycleWelcome\.projectsRoot/);
  assert.match(md, /\| Проект \| Задача/);
});

test('в папке нет сводки — тоже демо', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'сводка-'));
  assert.match(м.раздел(d, fs.readFileSync), /демо/i);
});

test('сломанный JSON — текст ошибки, без исключения', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'сводка-'));
  fs.writeFileSync(path.join(d, 'пульт-сводка.json'), '{ не json');
  const md = м.раздел(d, fs.readFileSync);
  assert.match(md, /не читается/);
  assert.doesNotMatch(md, /демо/i);
});

test('сводка без обязательных полей — текст ошибки', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'сводка-'));
  fs.writeFileSync(path.join(d, 'пульт-сводка.json'), '{"собран": "2026-10-09"}');
  assert.match(м.раздел(d, fs.readFileSync), /не читается.*задачи/);
});

test('настоящая сводка из папки читается', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'сводка-'));
  fs.writeFileSync(path.join(d, 'пульт-сводка.json'), JSON.stringify(сводка));
  assert.strictEqual(м.раздел(d, fs.readFileSync), м.markdown(сводка));
});

test('папка есть, но сводка не читается (это каталог) — ошибка, а не демо', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'сводка-'));
  fs.mkdirSync(path.join(d, 'пульт-сводка.json'));
  const md = м.раздел(d, fs.readFileSync);
  assert.match(md, /не читается/);
  assert.doesNotMatch(md, /демо/i);
});

test('разметка в чужих текстах погашена, перевод строки не ломает список', () => {
  const md = м.markdown({ ...сводка,
    сигналы: [{ проект: 'А*Б', текст: '<b>[x](y)</b>\nвторая', уровень: 'crit' }],
    задачи: [{ проект: 'П_1', задача: '`код`', причины: ['a\\b'] }] });
  assert.ok(md.includes('- **сбой** · А\\*Б: \\<b\\>\\[x\\](y)\\</b\\> вторая\n'), md);
  assert.ok(md.includes('| П\\_1 | \\`код\\` | a\\\\b |'), md);
});

test('сигнал без уровня — прочерк', () => {
  assert.match(м.markdown({ ...сводка, сигналы: [{ проект: 'А', текст: 'т' }] }), /- \*\*—\*\* · А: т/);
});
